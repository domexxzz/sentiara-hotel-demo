"""นาฬิกาของระบบ — เวลาไทยเสมอ **ห้าม UTC**

ทำไมถึงต้องมีไฟล์นี้
--------------------
ไทยเร็วกว่า UTC เจ็ดชั่วโมง งาน night audit ที่รันตอนตีสองจะได้วันที่เป็น
"เมื่อวาน" ถ้าอ่านเวลาแบบ UTC ทั้งที่ตั้งใจให้เป็นวันนี้ — ยอดขายทั้งคืน
ไปตกผิดวัน แล้วงบรายวันสองวันติดกันผิดพร้อมกันทั้งคู่

ใช้ออฟเซ็ตคงที่ +07:00 ไม่ใช่ `zoneinfo` เพราะสองเหตุผล
  * ไทยเลิกใช้เวลาออมแสงตั้งแต่ พ.ศ. 2519 ออฟเซ็ตจึงคงที่จริง ๆ
  * `zoneinfo` บนวินโดวส์ต้องลงแพ็กเกจ `tzdata` เพิ่ม — พึ่งพาน้อยกว่าคือพังยากกว่า

และไม่ใช้ `datetime.now()` เปล่า ๆ เพราะถ้าวันหนึ่งย้ายไปรันบนคลาวด์ที่ตั้ง
นาฬิกาเครื่องเป็น UTC ปัญหาเดิมจะกลับมาเงียบ ๆ โดยไม่มีอะไรฟ้อง

**ทุกที่ในระบบที่ต้องรู้เวลา ให้เรียกจากไฟล์นี้ที่เดียว** ห้ามเรียก
`datetime.utcnow()` หรือ `datetime.now()` ตรง ๆ ที่อื่น
"""
from __future__ import annotations

from datetime import date, datetime, timedelta, timezone

#: เวลามาตรฐานไทย · ออฟเซ็ตคงที่ ไม่มีเวลาออมแสง
TH = timezone(timedelta(hours=7), "ICT")


def now() -> datetime:
    """เวลาไทยตอนนี้

    คืนค่าแบบไม่ติด tzinfo มาด้วย เพราะคอลัมน์ DateTime ของ SQLite เก็บ
    แบบไม่มีโซนอยู่แล้ว ถ้าปนกันจะเทียบค่ากันไม่ได้ตอนอ่านออกมา
    ค่าที่เก็บทั้งฐานข้อมูลจึงเป็นเวลาไทยเหมือนกันหมด ไม่ต้องเดา
    """
    return datetime.now(TH).replace(tzinfo=None)


def today() -> date:
    """วันที่ตามเวลาไทย — ใช้ตัวนี้กับทุกอย่างที่เป็น 'วันทำการ'"""
    return now().date()
